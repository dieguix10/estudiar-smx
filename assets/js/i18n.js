(function () {
  'use strict';
  var lang = (document.documentElement.lang || '').toLowerCase().indexOf('ca') === 0 ? 'ca' : 'es';
  window.SMX_LANG = lang;
  window.SMX_UI = window.SMX_I18N[lang];

  window.SMX_T = function (key, vars) {
    var text = (window.SMX_UI && window.SMX_UI[key]) || key;
    if (!vars) return text;
    Object.keys(vars).forEach(function (name) {
      text = text.split('{' + name + '}').join(String(vars[name]));
    });
    return text;
  };
})();
